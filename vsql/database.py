"""Read-only database gateway with an optional, explicitly selected LAN compatibility mode.

Only the gateway can access database credentials. Local AI receives metadata but
never database rows/passwords. Live previews are generated by the SQL compiler.
"""
from __future__ import annotations

import ipaddress
import os
import re
import socket
import ssl
from contextlib import contextmanager
from dataclasses import dataclass
from typing import Iterator

from .models import Column, Table, QueryPlan, table_key
from .sql_builder import SQLBuilder, validate_plan, quote_identifier
from .security import check_generated_sql, check_sql_ast_if_available

PREVIEW_ROWS_DEFAULT = 100
METADATA_BATCH = 750
MAX_METADATA_COLUMNS = 100_000
ENGINE_PORTS = {"mysql": 3306, "postgres": 5432, "tsql": 1433}
TLS_MODES = {"verify", "trust", "legacy"}


@dataclass(eq=True)
class ConnectionConfig:
    kind: str = "mysql"
    host: str = "localhost"
    port: int = 3306
    database: str = ""
    user: str = ""
    password: str = ""  # RAM only, never put in workspace or local-AI prompt
    tls_mode: str = "verify"  # user has to opt into less secure modes
    ca_file: str = ""       # optional, internal-only; hidden in simple form
    odbc_driver: str = ""   # auto-select an installed Microsoft ODBC driver

    def validate(self):
        if self.kind not in ENGINE_PORTS:
            raise ValueError("Choose MySQL, PostgreSQL or SQL Server")
        if not self.host.strip() or not self.database.strip() or not self.user.strip():
            raise ValueError("Host, User and Database are required")
        if not isinstance(self.port, int) or not 1 <= self.port <= 65535:
            raise ValueError("Port must be between 1 and 65535")
        if self.tls_mode not in TLS_MODES:
            raise ValueError("Invalid TLS connection mode")
        if self.ca_file and self.tls_mode == "verify" and not os.path.isfile(self.ca_file):
            raise ValueError("CA certificate file not found. Select a valid PEM/CRT file provided by IT.")
        if any("\x00" in field for field in (
            self.host, self.user, self.database, self.password, self.ca_file
        )):
            raise ValueError("Invalid connection field")
        if any(ch in self.host for ch in ("/", "\\", ";", "@", "?", "#")):
            raise ValueError("Host must be an address or hostname, without http:// or a path")

    @property
    def local_host(self) -> bool:
        host = self.host.strip().lower().strip("[]")
        return host in ("localhost", "127.0.0.1", "::1")

    @property
    def internal_host(self) -> bool:
        host = self.host.strip().lower().strip("[]")
        if self.local_host or host.endswith((".local", ".internal", ".lan")):
            return True
        try:
            ip = ipaddress.ip_address(host)
            return ip.is_private or ip.is_loopback
        except ValueError:
            return False


def get_error_detail(error: BaseException, cfg: ConnectionConfig | None = None) -> str:
    """Return a human-actionable error without echoing credentials.

    Connection errors should be shown by Test Connection in the same window.
    """
    original = str(error)
    for secret in ((cfg.password if cfg else ""),):
        if secret:
            original = original.replace(secret, "[hidden]")
    original = re.sub(r"(?i)(password|pwd)\s*=\s*[^;\s]+", r"\1=[hidden]", original)
    safe_text = original[:350]
    low = safe_text.lower()
    if "pymysql is missing" in low or "driver is missing" in low or "pyodbc" in low and "install" in low:
        tip = "Driver missing: run install_windows.bat. SQL Server also needs Microsoft ODBC Driver 17/18."
    elif any(x in low for x in ("certificate", "ssl", "tls", "hostname mismatch", "verify failed", "secure connection")):
        if any(x in low for x in ("self-signed", "certificate verify failed", "certificate_verify_failed", "certificate chain")):
            tip = ("MySQL SSL certificate is not trusted. Preferred: ask IT for the company CA certificate, "
                   "then open Advanced and select 'Use CA certificate from IT'. "
                   "With IT approval for this internal server ONLY: select "
                   "'Internal TLS (unverified certificate)' and Test again. Do not choose unencrypted LAN by default.")
        else:
            tip = ("SSL/TLS certificate issue: request a trusted CA/hostname from IT. "
                   "Open Advanced to configure verified TLS or an explicitly approved internal connection mode.")
    elif any(x in low for x in ("access denied", "authentication failed", "password authentication", "login failed", "(1045", "28000")):
        tip = "Login rejected: check User/Password and whether this account may connect from your PC's IP."
    elif any(x in low for x in ("unknown database", "does not exist", "(1049", "3d000", "cannot open database")):
        tip = "Database not found or not accessible: verify the Database field and account permissions."
    elif any(x in low for x in ("timeout", "timed out", "refused", "10061", "2003", "08001", "name or service not known", "getaddrinfo", "network-related")):
        tip = "Network issue: verify Host/Port, VPN/LAN access, firewall and database listener."
    elif "no accessible tables" in low:
        tip = "Login succeeded, but no readable tables were found. Verify database name and SELECT/metadata permissions."
    elif "100000" in low:
        tip = "The database has too many columns for this session. Narrow database/schema access."
    elif "odbc" in low:
        tip = "SQL Server: check installed Microsoft ODBC Driver, SQL authentication and TLS settings."
    else:
        tip = "Check Host, User, Password, Database and Port. Use the full error below if IT needs to investigate."
    return tip + "\n" + safe_text


def _odbc_value(value: str) -> str:
    """ODBC bracket-escape values; supports ';' in strong passwords safely."""
    return "{" + value.replace("}", "}}") + "}"


class DatabaseGateway:
    """Database access stays separate from the AI and query-plan generation."""
    def __init__(self):
        self.config = ConnectionConfig()
        self.tables: dict[str, Table] = {}
        self.connected = False
        self.metadata_warnings: list[str] = []

    @property
    def dialect(self) -> str:
        return self.config.kind

    @property
    def description(self) -> str:
        if not self.connected:
            return "Not connected"
        names = {(t.catalog if self.config.kind == "tsql" else
                  self.config.database if self.config.kind == "postgres" else t.schema)
                 for t in self.tables.values()}
        return f"{self.config.kind.upper()} / {self.config.database}  ({len(names)} DBs visible)"

    def close(self):
        self.connected = False
        self.tables.clear()
        self.metadata_warnings.clear()
        self.config = ConnectionConfig()

    @staticmethod
    def _sql_server_driver(pyodbc, requested=""):
        available = pyodbc.drivers()
        if requested:
            if requested not in available:
                raise RuntimeError("Selected SQL Server ODBC driver is not installed: " + requested)
            return requested
        for driver in ("ODBC Driver 18 for SQL Server", "ODBC Driver 17 for SQL Server"):
            if driver in available:
                return driver
        raise RuntimeError("No Microsoft ODBC Driver 17/18 for SQL Server is installed")

    @contextmanager
    def _connect(self, cfg: ConnectionConfig | None = None) -> Iterator:
        cfg = cfg or self.config
        cfg.validate()
        if cfg.kind == "mysql":
            try:
                import pymysql
            except ImportError:
                pymysql = None
            if pymysql is not None:
                if cfg.tls_mode == "verify":
                    tls = None if cfg.local_host else ssl.create_default_context(cafile=cfg.ca_file or None)
                elif cfg.tls_mode == "trust":
                    # Encrypt without certificate verification only if explicitly selected.
                    tls = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
                    tls.check_hostname = False
                    tls.verify_mode = ssl.CERT_NONE
                else:
                    tls = None  # opt-in legacy compatibility, never an automatic downgrade
                conn = pymysql.connect(
                    host=cfg.host, port=cfg.port, user=cfg.user, password=cfg.password,
                    database=cfg.database, connect_timeout=7, read_timeout=12,
                    write_timeout=12, autocommit=True, ssl=tls, charset="utf8mb4",
                )
            else:
                # Optional compatibility with Windows installations that already use
                # mysql-connector-python (common in CSV-import applications).
                try:
                    import mysql.connector
                except ImportError as exc:
                    raise RuntimeError("No MySQL connector found. Run install_windows.bat") from exc
                options = dict(
                    host=cfg.host, port=cfg.port, user=cfg.user, password=cfg.password,
                    database=cfg.database, connection_timeout=7,
                    autocommit=True, charset="utf8mb4", use_pure=True,
                )
                if cfg.tls_mode == "legacy" or (cfg.tls_mode == "verify" and cfg.local_host):
                    options["ssl_disabled"] = True
                else:
                    options["ssl_disabled"] = False
                    options["ssl_verify_cert"] = cfg.tls_mode == "verify"
                    options["ssl_verify_identity"] = cfg.tls_mode == "verify"
                    if cfg.ca_file:
                        options["ssl_ca"] = cfg.ca_file
                conn = mysql.connector.connect(**options)
        elif cfg.kind == "postgres":
            try:
                import psycopg2
            except ImportError as exc:
                raise RuntimeError("PostgreSQL driver is missing; run install_windows.bat") from exc
            ssl_mode = ("disable" if cfg.local_host else "verify-full") if cfg.tls_mode == "verify" else (
                "require" if cfg.tls_mode == "trust" else "disable"
            )
            kwargs = dict(
                host=cfg.host, port=cfg.port, dbname=cfg.database, user=cfg.user,
                password=cfg.password, connect_timeout=7, sslmode=ssl_mode,
                options="-c default_transaction_read_only=on -c statement_timeout=10000",
            )
            if cfg.ca_file and cfg.tls_mode == "verify":
                kwargs["sslrootcert"] = cfg.ca_file
            conn = psycopg2.connect(**kwargs)
        else:
            try:
                import pyodbc
            except ImportError as exc:
                raise RuntimeError("Install pyodbc and Microsoft ODBC Driver 17 or 18") from exc
            driver = self._sql_server_driver(pyodbc, cfg.odbc_driver)
            server = cfg.host + ("," + str(cfg.port) if cfg.port else "")
            parts = [
                "DRIVER=" + _odbc_value(driver),
                "SERVER=" + _odbc_value(server),
                "DATABASE=" + _odbc_value(cfg.database),
                "Encrypt=" + ("no" if cfg.tls_mode == "legacy" else "yes"),
                "TrustServerCertificate=" + ("yes" if cfg.tls_mode == "trust" else "no"),
                "ApplicationIntent=ReadOnly",
                "UID=" + _odbc_value(cfg.user),
                "PWD=" + _odbc_value(cfg.password),
            ]
            conn = pyodbc.connect(";".join(parts), timeout=7, autocommit=False)
        try:
            yield conn
        finally:
            try:
                conn.rollback()
            finally:
                conn.close()

    def test_connection(self, cfg: ConnectionConfig) -> bool:
        cfg.validate()
        with self._connect(cfg) as conn:
            cursor = conn.cursor()
            try:
                if cfg.kind == "tsql":
                    cursor.timeout = 9
                cursor.execute("SELECT 1")
                value = cursor.fetchone()
                if not value or int(value[0]) != 1:
                    raise RuntimeError("The server did not return a valid test result")
            finally:
                cursor.close()
        return True

    def open(self, cfg: ConnectionConfig) -> dict[str, Table]:
        """Do not change the active session until accessible metadata was loaded."""
        cfg.validate()
        with self._connect(cfg) as conn:
            new_tables = self._introspect(conn, cfg)
        if not new_tables:
            raise RuntimeError("No accessible tables or columns were found. Check database permissions.")
        self.config = cfg
        self.tables = new_tables
        self.connected = True
        return new_tables

    def refresh_metadata(self) -> dict[str, Table]:
        """Re-read permitted table metadata without changing credentials or SQL context."""
        if not self.connected:
            raise RuntimeError("Connect to a database first")
        with self._connect(self.config) as conn:
            new_tables = self._introspect(conn, self.config)
        if not new_tables:
            raise RuntimeError("No readable tables found with the active login")
        self.tables = new_tables
        return new_tables

    def _introspect(self, conn, cfg: ConnectionConfig) -> dict[str, Table]:
        """Read all accessible locations *on this connection*, never customer rows.

        MySQL exposes all granted databases through INFORMATION_SCHEMA.COLUMNS;
        restricting TABLE_SCHEMA to the login's default database was the v0.3 bug.
        PostgreSQL exposes schemas within the connected database only.
        SQL Server can query metadata of accessible databases on the same server
        with properly escaped three-part identifiers.
        """
        tables: dict[str, Table] = {}
        self.metadata_warnings = []
        total = 0

        def collect_columns(cursor, catalog: str = ""):
            nonlocal total
            while True:
                batch = cursor.fetchmany(METADATA_BATCH)
                if not batch:
                    break
                total += len(batch)
                if total > MAX_METADATA_COLUMNS:
                    raise RuntimeError(
                        "More than 100000 metadata columns across accessible databases. "
                        "Ask IT to narrow metadata permissions; no data was modified."
                    )
                for schema, name, col, dtype, nullable, key in batch:
                    k = table_key(str(schema), str(name), catalog)
                    if k not in tables:
                        tables[k] = Table(str(schema), str(name), [], catalog=catalog)
                    tables[k].columns.append(Column(
                        str(col), str(dtype), str(nullable).upper() == "YES",
                        str(key).upper() == "PRI",
                    ))

        cur = conn.cursor()
        try:
            if cfg.kind == "mysql":
                # DATABASE = SCHEMA in MySQL. Never filter by cfg.database;
                # the database entered at login is just the default database.
                # INFORMATION_SCHEMA only shows objects visible to this user.
                cur.execute("""SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME,
                                      COLUMN_TYPE, IS_NULLABLE, COLUMN_KEY
                               FROM information_schema.COLUMNS
                               WHERE TABLE_SCHEMA NOT IN
                                    ('information_schema', 'mysql',
                                     'performance_schema', 'sys')
                               ORDER BY TABLE_SCHEMA, TABLE_NAME,
                                        ORDINAL_POSITION""")
                collect_columns(cur)
            elif cfg.kind == "postgres":
                # Different schemas in one PostgreSQL database can be joined.
                # Different PostgreSQL databases cannot be joined directly
                # without an explicitly configured foreign-data wrapper.
                cur.execute("""SELECT table_schema, table_name, column_name,
                                      data_type, is_nullable, ''
                               FROM information_schema.columns
                               WHERE table_catalog = current_database()
                                 AND table_schema NOT IN
                                     ('information_schema', 'pg_catalog')
                                 AND table_schema NOT LIKE 'pg_toast%'
                                 AND table_schema NOT LIKE 'pg_temp%'
                               ORDER BY table_schema, table_name,
                                        ordinal_position""")
                collect_columns(cur)
            else:
                # A separate INFORMATION_SCHEMA exists in *each* SQL Server
                # database. [db].INFORMATION_SCHEMA.COLUMNS is read-only.
                # Discover accessible databases without altering the active
                # connection's context (no USE or switching credentials).
                cur.timeout = 12
                cur.execute("""SELECT name FROM sys.databases
                               WHERE database_id > 4 AND state_desc = 'ONLINE'
                                 AND HAS_DBACCESS(name) = 1
                               ORDER BY name""")
                names = [str(row[0]) for row in cur.fetchall()]
                # Always consider the default selected database, even when
                # it is hidden by SQL Server metadata visibility rules.
                if cfg.database not in names:
                    names.insert(0, cfg.database)
                for catalog in dict.fromkeys(names):
                    db_name = quote_identifier(catalog, "tsql")
                    sql = ("SELECT TABLE_SCHEMA, TABLE_NAME, COLUMN_NAME, "
                           "DATA_TYPE, IS_NULLABLE, '' "
                           f"FROM {db_name}.INFORMATION_SCHEMA.COLUMNS "
                           "ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION")
                    try:
                        cur.execute(sql)
                    except Exception as exc:
                        # Some online DBs deny cross-database metadata even
                        # when HAS_DBACCESS=1. Skip but report the location.
                        self.metadata_warnings.append(
                            f"Could not list tables in {catalog}: "
                            f"{type(exc).__name__} (check cross-database metadata privileges)"
                        )
                        continue
                    collect_columns(cur, catalog=catalog)
            return tables
        finally:
            cur.close()

    def preview(self, plan: QueryPlan, rows: int = PREVIEW_ROWS_DEFAULT) -> tuple[list[str], list[tuple]]:
        if not self.connected:
            raise RuntimeError("Connect to a database before Preview")
        if plan.dialect != self.dialect:
            raise ValueError("Query database type does not match the active connection")
        rows = min(max(int(rows), 1), 200)
        validate_plan(plan, self.tables)
        compiler = SQLBuilder(plan, self.tables)
        generated = compiler.build(limit=rows, parameterized=True)
        inspect_sql = compiler.build(limit=rows, parameterized=False).sql
        report = check_generated_sql(inspect_sql)
        if not report.safe:
            raise PermissionError("Read-only check failed: " + report.message)
        ast_report = check_sql_ast_if_available(inspect_sql, self.dialect, required=True)
        if not ast_report.safe:
            raise PermissionError("SQL AST check failed: " + ast_report.message)
        with self._connect(self.config) as conn:
            cur = conn.cursor()
            try:
                if self.config.kind == "mysql":
                    cur.execute("START TRANSACTION READ ONLY")
                elif self.config.kind == "postgres":
                    conn.set_session(readonly=True)
                elif self.config.kind == "tsql":
                    cur.timeout = 10
                cur.execute(generated.sql, generated.params)
                headers = [d[0] for d in cur.description] if cur.description else []
                return headers, [tuple(row) for row in cur.fetchmany(rows)]
            finally:
                cur.close()
                conn.rollback()
